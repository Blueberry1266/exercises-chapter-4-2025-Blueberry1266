class Game:
    """Play a game."""

    def __init__(self, game, size):
        game.board = np.zeros((size, size))

    def play(self):
        """Play a game."""

        print("Playing life. Press ctrl + c to stop.")
        pyplot.ion()
        while True:
            self.move()
            self.show()
            pyplot.pause(0.0000005)

    def move(self):
        """Play a game."""

        stencil = np.array([[1, 1, 1], [1, 0, 1], [1, 1, 1]])
        neighbourcount = convolve2d(self.board, stencil, mode='same')

        for i in range(self.board.shape[0]):
            for j in range(self.board.shape[1]):
                self.board[i, j] = 1 if (neighbourcount[i, j] == 3
                                         or (neighbourcount[i, j] == 2
                                             and self.board[i, j])) else 0

    def __setitem__(self, key, value):
        """Play a game."""

        self.board[key] = value

    def show(self):
        """Play a game."""

        pyplot.clf()
        pyplot.matshow(self.board, fignum=0, cmap='binary')
        pyplot.show()

    def insert(self, pattern, place):
        """Play a game."""

        height = (len(pattern.grid)-1)//2
        width = (len(pattern.grid[0])-1)//2
        x, y = place[0], place[1]
        self.board[x-height:x+height+1, y-width:y+width+1] = pattern.grid


class Pattern:
    def __init__(self, grid):
        self.grid = grid

    def flip_vertical(self):
        new_grid = self.grid[::-1]
        return Pattern(new_grid)

    def flip_horizontal(self):
        new_grid = copy(self.grid)
        length_grid = len(self.grid[1])
        for j in range(len(self.grid)):
            for k in range(length_grid):
                new_grid[j][k] = self.grid[j][length_grid-1-k]
        return Pattern(new_grid)

    def flip_diag(self):
        new_grid = np.transpose(self.grid)
        return Pattern(new_grid)

    def rotate(self, n):
        res = self
        for j in range(n):
            res = res.flip_diag().flip_vertical()
        return res
